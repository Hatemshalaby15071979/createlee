"""Email delivery. Sending is ONLY ever called from the explicit approval endpoint.

No credentials configured  ->  a portable .eml draft is written to outputs/
so the user can send it from their own mail client. Createlee never stores or
guesses a user's personal mailbox credentials.
"""
from __future__ import annotations

import base64
import datetime as dt
import smtplib
from email.message import EmailMessage
from pathlib import Path

import config


def iso_now() -> str:
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def status() -> dict:
    ready = bool(config.SMTP_HOST and config.SMTP_USER and config.SMTP_PASSWORD and config.SMTP_FROM)
    return {
        "configured": ready,
        "host": config.SMTP_HOST or "(unset)",
        "port": config.SMTP_PORT,
        "from": config.SMTP_FROM or "(unset)",
        "security": config.SMTP_SECURITY,
        "mode": "smtp-send" if ready else "eml-draft",
    }


def _build_message(to: str, subject: str, body: str, attachments: list[Path]) -> EmailMessage:
    msg = EmailMessage()
    msg["From"] = config.SMTP_FROM or "createlee@localhost"
    msg["To"] = to
    msg["Subject"] = subject
    msg["Date"] = dt.datetime.now(dt.timezone.utc).strftime("%a, %d %b %Y %H:%M:%S +0000")
    msg["X-Createlee-Agent"] = config.AGENT_NAME
    msg["X-Createlee-Generated-At"] = iso_now()
    msg.set_content(body or "Generated by Createlee / Engeznee.\n")
    for path in attachments:
        p = Path(path)
        if not p.is_file():
            continue
        data = p.read_bytes()
        main, sub = _mime(p.suffix)
        msg.add_attachment(data, maintype=main, subtype=sub, filename=p.name)
    return msg


def _mime(suffix: str) -> tuple[str, str]:
    return {
        ".pdf": ("application", "pdf"),
        ".csv": ("text", "csv"),
        ".txt": ("text", "plain"),
        ".json": ("application", "json"),
        ".docx": ("application", "vnd.openxmlformats-officedocument.wordprocessingml.document"),
    }.get(suffix.lower(), ("application", "octet-stream"))


def _login(server: smtplib.SMTP, user: str, password: str) -> None:
    """AUTH LOGIN done by hand so we can capture the real code.

    Gmail closes the socket immediately after sending `535 5.7.8`, and
    smtplib.login() then raises SMTPServerDisconnected, hiding the reason.
    Doing the exchange with docmd() surfaces the 535 so the operator is told
    the credential was rejected instead of "connection closed".
    """
    try:
        code, resp = server.docmd("AUTH", "LOGIN")
        if code != 334:
            raise smtplib.SMTPAuthenticationError(code, resp)
        code, resp = server.docmd(base64.b64encode(user.encode()).decode())
        if code != 334:
            raise smtplib.SMTPAuthenticationError(code, resp)
        code, resp = server.docmd(base64.b64encode(password.encode()).decode())
        if code != 235:
            raise smtplib.SMTPAuthenticationError(code, resp)
    except smtplib.SMTPNotSupportedError:
        server.login(user, password)  # server does not offer AUTH LOGIN


def deliver(to: str, subject: str, body: str, attachments: list[Path],
            approved: bool = False) -> dict:
    """Approval is enforced by the caller; this is a second safety check."""
    if not approved:
        return {"ok": False, "mode": "blocked", "message": "Approval flag missing. Nothing was sent."}
    if not to or "@" not in to:
        return {"ok": False, "mode": "blocked", "message": "A valid recipient address is required."}

    files = [Path(p) for p in attachments if Path(p).is_file()]
    msg = _build_message(to, subject, body, files)

    if not status()["configured"]:
        stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        out = config.OUTPUT_DIR / f"createlee_email_draft_{stamp}.eml"
        out.write_bytes(msg.as_bytes())
        return {
            "ok": True, "mode": "eml-draft", "path": str(out), "filename": out.name,
            "message": ("SMTP credentials are not configured, so nothing was sent from your mailbox. "
                        "A ready-to-send .eml draft (with attachments) was created instead. "
                        "Set CREATELEE_SMTP_* in .env to enable real sending."),
            "attachments": [p.name for p in files],
        }

    def _attempt(host: str, port: int, security: str) -> None:
        if security == "ssl":
            server = smtplib.SMTP_SSL(host, port, timeout=30)
        else:
            server = smtplib.SMTP(host, port, timeout=30)
            if security == "starttls":
                server.starttls()
        with server:
            _login(server, config.SMTP_USER, config.SMTP_PASSWORD)
            server.send_message(msg)

    errors: list[str] = []
    try:
        _attempt(config.SMTP_HOST, config.SMTP_PORT, config.SMTP_SECURITY)
        return {"ok": True, "mode": "smtp-send", "to": to,
                "from": config.SMTP_FROM, "attachments": [p.name for p in files],
                "sent_at_iso8601": iso_now(),
                "message": f"Sent {len(files)} attachment(s) to {to}."}
    except smtplib.SMTPAuthenticationError as exc:
        detail = (exc.smtp_error or b"").decode(errors="replace").strip()
        auth_hint = (
            "Gmail rejected the app password (535 5.7.8 Username and Password not accepted). "
            "The .env values are fine; the credential is not. Regenerate the App Password at "
            "https://myaccount.google.com/apppasswords (2-Step Verification must be ON), paste "
            "the 16 characters, and restart the app. Plain account passwords never work over SMTP.")
        return _save_draft(msg, "eml-draft-fallback",
                           f"SMTP authentication failed: {detail}. {auth_hint}", errors)
    except smtplib.SMTPServerDisconnected as exc:
        # Gmail sometimes tears the socket down before smtplib reads the 535.
        return _save_draft(msg, "eml-draft-fallback",
                           "SMTP connection was closed during authentication. On Gmail this "
                           "almost always means the App Password was rejected (535 5.7.8). "
                           "Regenerate it at https://myaccount.google.com/apppasswords, paste "
                           "the 16 characters, and restart the app. "
                           f"({type(exc).__name__}: {exc})", errors)
    except Exception as exc:  # noqa: BLE001
        errors.append(f"{config.SMTP_SECURITY} {config.SMTP_PORT}: {type(exc).__name__}: {exc}")
        # Port 587 blocked or dropping is common on some networks; try implicit TLS 465 once.
        if config.SMTP_SECURITY != "ssl" and config.SMTP_PORT != 465:
            try:
                _attempt(config.SMTP_HOST, 465, "ssl")
                return {"ok": True, "mode": "smtp-send", "to": to, "from": config.SMTP_FROM,
                        "attachments": [p.name for p in files], "sent_at_iso8601": iso_now(),
                        "message": f"Sent {len(files)} attachment(s) to {to} via SSL 465."}
            except smtplib.SMTPAuthenticationError as exc2:
                detail = (exc2.smtp_error or b"").decode(errors="replace").strip()
                return _save_draft(msg, "eml-draft-fallback",
                                   f"SMTP authentication failed: {detail} (also tried SSL 465). "
                                   "Regenerate the Gmail App Password and restart.", errors)
            except Exception as exc2:  # noqa: BLE001
                errors.append(f"ssl 465: {type(exc2).__name__}: {exc2}")
        return _save_draft(msg, "eml-draft-fallback",
                           "SMTP send failed (" + " | ".join(errors) +
                           "). Nothing was sent", errors)


def _save_draft(msg: EmailMessage, mode: str, reason: str, errors: list[str]) -> dict:
    stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    out = config.OUTPUT_DIR / f"createlee_email_draft_fallback_{stamp}.eml"
    out.write_bytes(msg.as_bytes())
    return {"ok": False, "mode": mode, "path": str(out), "errors": errors,
            "message": reason + "; an .eml draft was saved instead."}
